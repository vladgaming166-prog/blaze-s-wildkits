package com.blaze.wildkits.kit;

/**
 * Primary gear quality band for premium WildKits generation.
 */
public enum GearBand {
    /** Mostly iron with occasional diamond pieces */
    IRON,
    /** Mostly diamond, sometimes mixed iron/diamond */
    DIAMOND,
    /** Diamond + partial netherite (1-2 pieces) */
    NETHERITE_PARTIAL,
    /** Rare full netherite set */
    FULL_NETHERITE
}
